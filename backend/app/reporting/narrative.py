"""Optional assisted writing on top of the deterministic report (FSD RF7 / S7).

The deterministic report is the product: the nine sections of both versions are
always generated by rules from the analysed data. Assisted writing is an
*optional* extra that only runs when a provider key is configured. There are
three explicit states, and none of them means the report is incomplete:

* ``no_configurada``: no key in the environment; nothing was requested;
* ``deshabilitada_por_error``: a key exists but the section kept the
  deterministic text because of a timeout, a transport error, an HTTP error or
  a guard rejection;
* ``aplicada``: the provider answered and the guard accepted the rewrite.

`nan_base_url` and `nan_model` are configuration, not code: any
OpenAI-compatible provider works, and `reasoning_effort` is forwarded as given.

Nothing here decides findings, levels or counts. The model receives a closed
brief and is asked to rewrite; `app.reporting.guard` rejects anything it cannot
verify. The key never enters a log line, a response or an exception message.
"""

from __future__ import annotations

import json
import logging
import threading
from dataclasses import dataclass
from typing import Any

import httpx

from app.config import Settings

# Narrative states. `plantilla` marks a section that never uses assisted
# writing by design (evidence lists, rule justifications, limitations).
NARRATIVE_APPLIED = "aplicada"
NARRATIVE_NOT_CONFIGURED = "no_configurada"
NARRATIVE_DISABLED_BY_ERROR = "deshabilitada_por_error"
NARRATIVE_TEMPLATE = "plantilla"
NARRATIVE_PARTIAL = "parcial"

NOT_CONFIGURED_REASON = (
    "No hay una clave de API configurada para la redacción asistida; "
    "el informe se genera con el motor de reglas."
)
EMPTY_ANSWER_REASON = "La respuesta del proveedor de IA no contiene texto utilizable."
TOO_LONG_REASON = "La respuesta del proveedor de IA superó la longitud máxima admitida."
TIMEOUT_REASON = "El proveedor de IA no respondió dentro del tiempo límite."
CONNECTION_REASON = "No se pudo conectar con el proveedor de IA."
BUSY_REASON = "Hay demasiadas solicitudes de redacción asistida en curso."
UNPROCESSABLE_REASON = "El proveedor de IA devolvió una respuesta no procesable."

SYSTEM_PROMPT = (
    "Eres un redactor de informes de seguridad en español. REESCRIBES el borrador que "
    "recibes; no analizas y no decides nada. Reglas obligatorias: 1) no añadas hallazgos, "
    "incidentes, cifras, fechas, direcciones ni conclusiones que no estén en los hechos "
    "verificados; 2) no cambies la criticidad de ningún incidente; 3) no cites ningún "
    "Log_ID que no aparezca en los hechos, y no cites ninguno cuando la instrucción lo "
    "prohíba; 4) no inventes identificadores INC-; 5) conserva todas las entidades y "
    "cifras del borrador; 6) escribe español neutro en párrafos planos, sin markdown, "
    "sin tablas y sin encabezados."
)

REQUEST_TIMEOUT = httpx.Timeout(connect=5.0, read=30.0, write=10.0, pool=10.0)
MAX_COMPLETION_CHARS = 6000
MAX_SOURCE_CHARS = 12000
MAX_TOKENS = 1200
TEMPERATURE = 0.2
# The provider allows 7 concurrent requests per key; stay below it and never
# queue a request for longer than the connect timeout.
MAX_CONCURRENT_REQUESTS = 4
SEMAPHORE_TIMEOUT = 5.0
SSE_DATA_PREFIX = "data:"
SSE_DONE = "[DONE]"

logger = logging.getLogger(__name__)

_in_flight = threading.BoundedSemaphore(MAX_CONCURRENT_REQUESTS)


@dataclass(frozen=True, slots=True)
class Narrative:
    """Result of one assisted-writing attempt, with its explicit state."""

    text: str
    status: str
    reason: str | None = None


def _clip(text: str, limit: int) -> str:
    """Cut at a paragraph boundary so a clipped prompt stays readable."""
    if len(text) <= limit:
        return text
    cut = text.rfind("\n\n", 0, limit)
    return text[: cut if cut > 0 else limit]


def _messages(instruction: str, source: str, facts: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": (
                "INSTRUCCIÓN\n"
                f"{instruction}\n\n"
                "HECHOS VERIFICADOS (única fuente permitida)\n"
                f"{_clip(facts, MAX_SOURCE_CHARS)}\n\n"
                "BORRADOR DETERMINÍSTICO A REESCRIBIR\n"
                f"{_clip(source, MAX_SOURCE_CHARS)}"
            ),
        },
    ]


class NarrativeClient:
    """Streaming client for one OpenAI-compatible chat completions endpoint."""

    def __init__(self, settings: Settings, transport: httpx.BaseTransport | None = None) -> None:
        self._settings = settings
        self._transport = transport

    @property
    def enabled(self) -> bool:
        return bool(self._settings.nan_api_key.strip())

    def describe(self) -> dict[str, Any]:
        """Non-secret description of the configured provider."""
        return {
            "configurada": self.enabled,
            "proveedor": self._settings.nan_base_url,
            "modelo": self._settings.nan_model,
            "razonamiento": self._settings.nan_reasoning_effort,
        }

    def rewrite(self, *, instruction: str, source: str, facts: str) -> Narrative:
        """Ask the provider to rewrite one section, degrading gracefully."""
        if not self.enabled:
            return Narrative("", NARRATIVE_NOT_CONFIGURED, NOT_CONFIGURED_REASON)

        if not _in_flight.acquire(timeout=SEMAPHORE_TIMEOUT):
            return Narrative("", NARRATIVE_DISABLED_BY_ERROR, BUSY_REASON)
        try:
            return self._request(_messages(instruction, source, facts))
        finally:
            _in_flight.release()

    def _request(self, messages: list[dict[str, str]]) -> Narrative:
        payload = {
            "model": self._settings.nan_model,
            "messages": messages,
            "stream": True,
            "temperature": TEMPERATURE,
            "max_tokens": MAX_TOKENS,
            "reasoning_effort": self._settings.nan_reasoning_effort,
        }
        url = f"{self._settings.nan_base_url.rstrip('/')}/chat/completions"
        headers = {
            "authorization": f"Bearer {self._settings.nan_api_key}",
            "content-type": "application/json",
            "accept": "text/event-stream",
        }

        try:
            with httpx.Client(timeout=REQUEST_TIMEOUT, transport=self._transport) as client:
                with client.stream("POST", url, headers=headers, json=payload) as response:
                    if response.status_code != httpx.codes.OK:
                        return self._failure(
                            f"El proveedor de IA respondió con un error HTTP "
                            f"{response.status_code}."
                        )
                    text, reason = self._read_stream(response)
        except httpx.TimeoutException:
            return self._failure(TIMEOUT_REASON)
        except httpx.ConnectError:
            return self._failure(CONNECTION_REASON)
        except httpx.HTTPError:
            return self._failure(CONNECTION_REASON)
        except (OSError, ValueError):
            return self._failure(EMPTY_ANSWER_REASON)
        except Exception:  # noqa: BLE001 - the report must never fail because of the provider
            return self._failure(UNPROCESSABLE_REASON)

        if reason is not None:
            return self._failure(reason)
        return Narrative(text, NARRATIVE_APPLIED, None)

    def _failure(self, reason: str) -> Narrative:
        logger.info("assisted writing unavailable: reason=%s", reason)
        return Narrative("", NARRATIVE_DISABLED_BY_ERROR, reason)

    @staticmethod
    def _read_stream(response: httpx.Response) -> tuple[str, str | None]:
        """Join the SSE deltas of one completion; bound memory and length."""
        parts: list[str] = []
        total = 0
        for line in response.iter_lines():
            stripped = line.strip()
            if not stripped or not stripped.startswith(SSE_DATA_PREFIX):
                continue
            data = stripped[len(SSE_DATA_PREFIX) :].strip()
            if not data:
                continue
            if data == SSE_DONE:
                break
            try:
                chunk = json.loads(data)
            except ValueError:
                return "", EMPTY_ANSWER_REASON
            for choice in chunk.get("choices") or ():
                content = (choice.get("delta") or {}).get("content")
                if not content:
                    continue
                parts.append(content)
                total += len(content)
                if total > MAX_COMPLETION_CHARS:
                    return "", TOO_LONG_REASON
        text = "".join(parts).strip()
        if not text:
            return "", EMPTY_ANSWER_REASON
        return text, None
